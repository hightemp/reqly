//! Generates `commands.ts`: a typed map of command name → input/output.

use crate::registry::Registry;

pub fn render_commands_ts<C: Send + Sync + 'static>(registry: &Registry<C>) -> String {
    let mut out =
        String::from("// This file was generated by reqly-api. Do not edit manually.\n\n");
    for (name, stem) in registry.ts_types() {
        out.push_str(&format!("import type {{ {name} }} from \"./{stem}\";\n"));
    }
    out.push_str("\nexport type Commands = {\n");
    for sig in registry.signatures() {
        out.push_str(&format!(
            "  \"{}\": {{ input: {}; output: {} }};\n",
            sig.name, sig.input, sig.output
        ));
    }
    out.push_str("};\n\nexport type CommandName = keyof Commands;\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::commands::registry;

    #[test]
    fn renders_command_map() {
        let ts = render_commands_ts(&registry());
        assert!(ts.starts_with("// This file was generated by reqly-api."));
        assert!(ts.contains("import type { AppInfoOutput } from \"./AppInfoOutput\";"));
        assert!(ts.contains("\"app.info\": { input: Empty; output: AppInfoOutput };"));
        assert!(ts.contains("export type CommandName = keyof Commands;"));
    }

    /// Writes the generated file next to ts-rs output. CI fails if it is stale.
    #[test]
    fn export_commands_ts() {
        let dir = std::env::var("TS_RS_EXPORT_DIR").expect("set in .cargo/config.toml");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            format!("{dir}/commands.ts"),
            render_commands_ts(&registry()),
        )
        .unwrap();
    }
}
