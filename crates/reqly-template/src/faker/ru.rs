/// Feminine form of a masculine last name.
pub fn feminine(last: &str) -> String {
    if let Some(stem) = last.strip_suffix("ский") {
        format!("{stem}ская")
    } else if let Some(stem) = last.strip_suffix("цкий") {
        format!("{stem}цкая")
    } else if ["ов", "ев", "ёв", "ин", "ын"]
        .iter()
        .any(|s| last.ends_with(s))
    {
        format!("{last}а")
    } else {
        last.to_string()
    }
}

/// Latin transliteration for e-mail and user names.
pub fn translit(s: &str) -> String {
    s.chars()
        .map(|c| match c.to_lowercase().next().unwrap_or(c) {
            'а' => "a",
            'б' => "b",
            'в' => "v",
            'г' => "g",
            'д' => "d",
            'е' => "e",
            'ё' => "e",
            'ж' => "zh",
            'з' => "z",
            'и' => "i",
            'й' => "y",
            'к' => "k",
            'л' => "l",
            'м' => "m",
            'н' => "n",
            'о' => "o",
            'п' => "p",
            'р' => "r",
            'с' => "s",
            'т' => "t",
            'у' => "u",
            'ф' => "f",
            'х' => "kh",
            'ц' => "ts",
            'ч' => "ch",
            'ш' => "sh",
            'щ' => "sch",
            'ъ' => "",
            'ы' => "y",
            'ь' => "",
            'э' => "e",
            'ю' => "yu",
            'я' => "ya",
            '-' => "-",
            ' ' => ".",
            _ => "",
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn feminine_forms() {
        assert_eq!(feminine("Иванов"), "Иванова");
        assert_eq!(feminine("Никитин"), "Никитина");
        assert_eq!(feminine("Островский"), "Островская");
        assert_eq!(feminine("Соловьёв"), "Соловьёва");
    }

    #[test]
    fn transliteration() {
        assert_eq!(translit("Юлия Щукина"), "yuliya.schukina");
    }
}
